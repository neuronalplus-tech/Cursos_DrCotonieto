-- El alumno pide la encuesta de SU curso; si aún no existe la
-- crea con la pregunta por omisión y la devuelve. Así el directivo
-- no tiene que crearla a mano por cada curso. SECURITY DEFINER
-- porque el RLS de `encuestas` no permite insertar a un alumno.
-- El `on conflict` cubre la carrera de dos alumnos que terminan
-- a la vez: el segundo recibe la fila existente, no un error.
create or replace function public.encuesta_del_curso(p_curso integer)
returns setof public.encuestas
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  insert into public.encuestas as e (curso_id) values (p_curso)
  on conflict (curso_id) do update set activa = e.activa
  returning e.*;
end;
$$;
revoke all on function public.encuesta_del_curso(integer) from public;
grant execute on function public.encuesta_del_curso(integer) to authenticated;

-- El directivo ve el NPS por curso de SU organización. Verifica
-- que administra esa organización antes de devolver filas: sin
-- eso, cualquier admin podría leer el NPS de otro cliente.
create or replace function public.nps_organizacion(p_org bigint)
returns table (
  curso_id      bigint,
  titulo        text,
  respuestas    bigint,
  promotores    bigint,
  pasivos       bigint,
  detractores   bigint,
  nps           int
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not (public.es_admin() or public.es_admin_de(p_org)) then
    return;
  end if;
  return query
  select
    c.id::bigint,
    c.titulo::text,
    count(r.id)::bigint,
    count(*) filter (where r.puntaje >= 9)::bigint,
    count(*) filter (where r.puntaje between 7 and 8)::bigint,
    count(*) filter (where r.puntaje <= 6)::bigint,
    case when count(r.id) < 10 then null
      else round((count(*) filter (where r.puntaje >= 9))::numeric
        / count(r.id) * 100
        - (count(*) filter (where r.puntaje <= 6))::numeric
        / count(r.id) * 100)::int
    end
  from public.cursos c
  join public.encuestas e on e.curso_id = c.id
  left join public.respuestas_encuesta r on r.encuesta_id = e.id
  where c.organizacion_id = p_org
  group by c.id, c.titulo
  having count(r.id) > 0
  order by c.titulo;
end;
$$;
revoke all on function public.nps_organizacion(bigint) from public;
grant execute on function public.nps_organizacion(bigint) to authenticated;

notify pgrst, 'reload schema';

