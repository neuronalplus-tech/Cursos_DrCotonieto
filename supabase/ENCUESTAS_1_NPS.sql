-- =============================================================
--  ENCUESTAS 1 — NPS AL TERMINAR EL CURSO (F5-3, parte 1)
--
--  QUÉ RESUELVE
--  Hoy nadie mide si el alumno recomendaría el curso. El NPS es
--  una pregunta (0-10) + comentario opcional, al terminar. Es la
--  métrica que un directivo entiende sin explicación.
--
--  QUÉ HACE
--  Tablas `encuestas` (una por curso, creada al activar) y
--  `respuestas_encuesta` (una por alumno+encuesta, upsert). RLS:
--  el alumno responde lo suyo; quien administra lee lo de su
--  organización.
--
--  QUÉ NO HACE
--  No obliga a responder para ver la constancia ni bloquea nada.
--  Una encuesta que chantajea («responde o no hay constancia»)
--  consigue respuestas falsas, no datos.
--
--  CÓMO USARLO
--  Supabase -> SQL Editor -> New query -> pega esto -> Run.
--  Idempotente.
-- =============================================================

create table if not exists public.encuestas (
  id              bigint generated by default as identity primary key,
  curso_id        integer not null references public.cursos(id)
    on delete cascade,
  titulo          text not null default '¿Recomendarías este curso?',
  activa          boolean not null default true,
  creado_en       timestamptz not null default now()
);

create unique index if not exists encuestas_curso_idx
  on public.encuestas (curso_id);

create table if not exists public.respuestas_encuesta (
  id           bigint generated by default as identity primary key,
  encuesta_id  bigint not null references public.encuestas(id)
    on delete cascade,
  usuario_id   uuid not null references auth.users(id)
    on delete cascade,
  puntaje      int not null check (puntaje between 0 and 10),
  comentario   text,
  creado_en    timestamptz not null default now()
);

-- Una respuesta por alumno y encuesta: responder dos veces
-- actualiza, no duplica. Así el NPS no se infla a clics.
create unique index if not exists respuestas_encuesta_unica_idx
  on public.respuestas_encuesta (encuesta_id, usuario_id);

-- La encuesta la lee cualquiera con sesión (el alumno la necesita
-- para responder); las respuestas solo su dueño y la plataforma.
alter table public.encuestas enable row level security;
alter table public.respuestas_encuesta enable row level security;

drop policy if exists "encuestas_select" on public.encuestas;
create policy "encuestas_select" on public.encuestas
  for select to authenticated using (true);

drop policy if exists "encuestas_admin" on public.encuestas;
create policy "encuestas_admin" on public.encuestas
  for all to authenticated
  using (public.es_admin()) with check (public.es_admin());

drop policy if exists "respuestas_propia" on public.respuestas_encuesta;
create policy "respuestas_propia" on public.respuestas_encuesta
  for all to authenticated
  using (usuario_id = auth.uid()) with check (usuario_id = auth.uid());

drop policy if exists "respuestas_admin" on public.respuestas_encuesta;
create policy "respuestas_admin" on public.respuestas_encuesta
  for select to authenticated using (public.es_admin());

