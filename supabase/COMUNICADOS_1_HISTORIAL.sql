-- =============================================================
--  COMUNICADOS 1 — HISTORIAL Y PROGRAMADO (F5-1, parte 1: base)
--
--  QUÉ RESUELVE
--  Hoy un comunicado vive en el estado de React: se envía y se
--  olvida. Sin historial no se sabe qué se mandó, a quién, ni
--  cuándo; sin programado no se deja listo el recordatorio del
--  taller de mañana.
--
--  QUÉ HACE ESTE SCRIPT (solo base, sin tocar el envío actual)
--  Tabla `comunicados`: asunto, cuerpo, canal, destino, estado,
--  programado_para, enviado_en, conteos. RLS: quien administra la
--  organización escribe y lee lo suyo; nadie más.
--
--  QUÉ NO HACE (viene en la parte 2, front)
--  No cambia el envío actual (Apps Script + WhatsApp). El front
--  guardará aquí cada envío y leerá el historial. Programar =
--  guardar en estado `programado`; el envío lo dispara quien lo
--  programó al abrir el panel (sin cron en el plan gratuito).
--
--  CÓMO USARLO
--  Supabase -> SQL Editor -> New query -> pega esto -> Run.
--  Idempotente.
-- =============================================================

create table if not exists public.comunicados (
  id              bigint generated by default as identity primary key,
  organizacion_id bigint references public.organizaciones(id)
    on delete cascade,
  canal           text not null default 'correo',
  asunto          text not null default '',
  cuerpo          text not null default '',
  destino         text not null default 'todos',
  destino_detalle jsonb not null default '{}'::jsonb,
  estado          text not null default 'enviado',
  programado_para timestamptz,
  enviado_en      timestamptz,
  total           int not null default 0,
  creador_email   text,
  creado_en       timestamptz not null default now()
);

-- Quien administra la organización lee y escribe lo suyo.
-- Sin política de borrado a propósito: el historial no se
-- reescribe; un comunicado erróneo se corrige con otro.
alter table public.comunicados enable row level security;

drop policy if exists "comunicados_select" on public.comunicados;
create policy "comunicados_select" on public.comunicados
  for select to authenticated
  using (public.es_admin_de(organizacion_id));

drop policy if exists "comunicados_insert" on public.comunicados;
create policy "comunicados_insert" on public.comunicados
  for insert to authenticated
  with check (public.es_admin_de(organizacion_id));

-- Actualizar solo lo propio y solo para marcar envío o
-- reprogramar: no para reescribir el historial.
drop policy if exists "comunicados_update" on public.comunicados;
create policy "comunicados_update" on public.comunicados
  for update to authenticated
  using (public.es_admin_de(organizacion_id))
  with check (public.es_admin_de(organizacion_id));

notify pgrst, 'reload schema';

