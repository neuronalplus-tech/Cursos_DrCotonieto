-- =============================================================
--  WHATSAPP EN COMUNICADOS + BAJA DE CUENTAS
--
--  QUÉ RESUELVE
--  1. Un comunicado solo podía salir por correo. Ahora también por
--     WhatsApp, con mensajes guardados que se editan desde el mismo
--     apartado (`plantillas_whatsapp`).
--  2. No había dónde guardar un número. Ahora hay dos sitios, y la
--     diferencia entre ellos es lo importante de este archivo:
--
--       · `perfiles.whatsapp` — el que la persona escribe en SU
--         perfil. Lo ve y lo cambia ella.
--       · `contactos_admin.whatsapp` — el que capturas tú cuando la
--         persona no lo puso. Vive en OTRA tabla, no en su perfil.
--
--     Esto no es manía de orden: `perfiles` es legible por su dueño
--     (política `perfil_select`), así que una columna más ahí la
--     podría leer cualquiera desde la API aunque la pantalla no la
--     pinte, y vería un dato que él no escribió. Con tabla aparte y
--     RLS de solo-admin, el alumno no puede verla ni sabiendo pedirla.
--     Nadie se pregunta por qué el doctor editó su perfil.
--
--  3. Se podía dar y quitar acceso a cursos, pero no dar de baja a
--     nadie: las cuentas de prueba y las que nunca entraron se
--     quedaban para siempre. `eliminar_usuario()` las borra de
--     verdad, con dos frenos: no borra a quien ya tiene constancia
--     emitida (el folio es verificable en público y quedaría roto) y
--     no borra administradores ni a ti mismo.
--
--  CÓMO SE INSTALA
--  Supabase -> SQL Editor -> New query -> pega esto -> Run.
--  Correr ANTES: ALTA_PUBLICA_2_TANDAS.sql.
--  Es idempotente: volver a correrlo no borra datos ni duplica nada.
-- =============================================================

-- -------------------------------------------------------------
-- 1) El número de la propia persona (lo escribe ella, en su perfil)
-- -------------------------------------------------------------
alter table public.perfiles
  add column if not exists whatsapp text;

-- -------------------------------------------------------------
-- 2) El número que captura el admin — tabla aparte, invisible
--    para el alumno
-- -------------------------------------------------------------
create table if not exists public.contactos_admin (
  usuario_id uuid primary key references auth.users(id) on delete cascade,
  whatsapp text,
  nota text,
  actualizado_el timestamptz not null default now(),
  actualizado_por text
);

alter table public.contactos_admin enable row level security;

-- Sin política de SELECT para el dueño: a propósito. El alumno no
-- tiene forma de leer esta fila ni pidiéndola directamente.
drop policy if exists "contactos_admin_todo" on public.contactos_admin;
create policy "contactos_admin_todo" on public.contactos_admin
  for all to authenticated
  using (public.es_admin())
  with check (public.es_admin());

comment on table public.contactos_admin is
  'Números de contacto que captura el admin. Deliberadamente fuera de `perfiles`: el alumno no debe verlos (ver cabecera de WHATSAPP_Y_BAJAS.sql).';

-- -------------------------------------------------------------
-- 3) Mensajes de WhatsApp guardados
--
--    Un comunicado por WhatsApp se escribe una vez y se reusa: el
--    recordatorio del taller, el aviso de la constancia, el enlace
--    de la sesión. Los marcadores {{nombre}} y {{curso}} los sustituye
--    el panel al armar cada mensaje.
-- -------------------------------------------------------------
create table if not exists public.plantillas_whatsapp (
  id bigint generated by default as identity primary key,
  organizacion_id bigint references public.organizaciones(id) on delete cascade,
  nombre text not null,
  texto text not null,
  orden integer not null default 0,
  creado_el timestamptz not null default now()
);

alter table public.plantillas_whatsapp enable row level security;

drop policy if exists "plantillas_whatsapp_todo" on public.plantillas_whatsapp;
create policy "plantillas_whatsapp_todo" on public.plantillas_whatsapp
  for all to authenticated
  using (public.es_admin())
  with check (public.es_admin());

-- -------------------------------------------------------------
-- 4) Los números, ya resueltos, para el panel
--
--    Devuelve UN número por persona: el suyo si lo puso, y si no, el
--    que capturaste tú. `origen` dice cuál de los dos es, que es lo
--    que el panel necesita para no dejarte en la duda de si ese
--    número lo confirmó la persona o lo apuntaste de una lista.
-- -------------------------------------------------------------
create or replace function public.listar_whatsapp()
returns table (
  usuario_id uuid,
  email text,
  whatsapp text,
  origen text
)
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  v_email text;
begin
  v_email := auth.jwt() ->> 'email';
  if v_email is not null and not exists (
    select 1 from public.admins a where a.email = v_email
  ) then
    raise exception 'No autorizado';
  end if;

  return query
    select u.id,
           u.email::text,
           coalesce(nullif(btrim(p.whatsapp), ''), nullif(btrim(c.whatsapp), '')),
           case
             when nullif(btrim(p.whatsapp), '') is not null then 'perfil'
             when nullif(btrim(c.whatsapp), '') is not null then 'admin'
             else null
           end
      from auth.users u
      left join public.perfiles p on p.id = u.id
      left join public.contactos_admin c on c.usuario_id = u.id;
end
$$;

revoke all on function public.listar_whatsapp() from public;
grant execute on function public.listar_whatsapp() to authenticated;

-- -------------------------------------------------------------
-- 5) Qué se pierde si borro a esta persona
--
--    Se consulta ANTES de borrar, para que la confirmación diga
--    números concretos en vez de «¿seguro?».
-- -------------------------------------------------------------
create or replace function public.resumen_borrado_usuario(p_usuario uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  v_email text;
  v_obj text;
  v_constancias integer := 0;
  v_cursos integer := 0;
  v_progreso integer := 0;
  v_es_admin boolean := false;
begin
  v_email := auth.jwt() ->> 'email';
  if v_email is not null and not exists (
    select 1 from public.admins a where a.email = v_email
  ) then
    raise exception 'No autorizado';
  end if;

  select u.email::text into v_obj from auth.users u where u.id = p_usuario;
  if v_obj is null then raise exception 'Esa cuenta ya no existe'; end if;

  -- Aislamiento entre organizaciones: un admin de un cliente no puede
  -- NI SIQUIERA VER el resumen de borrado de alguien ajeno (si no, esta
  -- función servía de oráculo de datos de otros inquilinos). El admin de
  -- plataforma (es_admin) sí; un admin de organización solo de su gente.
  if v_email is not null
     and not public.es_admin()
     and not public.es_alumno_de_org_que_administro(p_usuario) then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  select count(*) into v_constancias from public.constancias where usuario_id = p_usuario;
  select count(*) into v_cursos      from public.acceso      where usuario_id = p_usuario;
  select count(*) into v_progreso    from public.progreso_usuario where usuario_id = p_usuario;
  select exists (select 1 from public.admins a where a.email = v_obj) into v_es_admin;

  return jsonb_build_object(
    'email', v_obj,
    'constancias', v_constancias,
    'cursos', v_cursos,
    'progreso', v_progreso,
    'esAdmin', v_es_admin,
    'esTuCuenta', lower(coalesce(v_email, '')) = lower(v_obj),
    'sePuede', v_constancias = 0 and not v_es_admin
               and lower(coalesce(v_email, '')) <> lower(v_obj)
  );
end
$$;

revoke all on function public.resumen_borrado_usuario(uuid) from public;
grant execute on function public.resumen_borrado_usuario(uuid) to authenticated;

-- -------------------------------------------------------------
-- 6) Borrar la cuenta de verdad
--
--    `p_confirmacion` tiene que venir con el correo exacto de quien
--    se va a borrar. No es un adorno: es lo que impide que un clic
--    en la fila equivocada borre a quien no era, porque el correo lo
--    teclea quien borra.
--
--    Las filas dependientes se recorren por catálogo (toda tabla de
--    `public` con una columna `usuario_id`) en vez de a mano. Escrito
--    a mano, cada tabla nueva —y en esta base salen seguido— dejaría
--    un resto que impide el borrado con un error de llave foránea
--    imposible de leer.
-- -------------------------------------------------------------
create or replace function public.eliminar_usuario(p_usuario uuid, p_confirmacion text)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_email text;
  v_obj text;
  v_resumen jsonb;
  v_tabla record;
  v_borradas jsonb := '{}'::jsonb;
  v_n integer;
begin
  v_email := auth.jwt() ->> 'email';
  if v_email is not null and not exists (
    select 1 from public.admins a where a.email = v_email
  ) then
    raise exception 'No autorizado';
  end if;

  -- resumen_borrado_usuario ya valida el aislamiento entre organizaciones
  -- y lanza si el objetivo es de otro inquilino; esta llamada hereda esa
  -- protección antes de borrar nada.
  v_resumen := public.resumen_borrado_usuario(p_usuario);
  v_obj := v_resumen ->> 'email';

  if lower(btrim(coalesce(p_confirmacion, ''))) <> lower(v_obj) then
    raise exception 'La confirmación no coincide con el correo de la cuenta';
  end if;
  if (v_resumen ->> 'esTuCuenta')::boolean then
    raise exception 'No puedes borrar tu propia cuenta desde aquí';
  end if;
  if (v_resumen ->> 'esAdmin')::boolean then
    raise exception 'Esa cuenta es administradora: quítale el rol antes de borrarla';
  end if;
  if (v_resumen ->> 'constancias')::integer > 0 then
    raise exception 'Esa persona tiene % constancia(s) emitida(s): su folio es verificable en público y dejaría de validar. Si aun así hay que borrarla, elimina primero sus constancias.',
      (v_resumen ->> 'constancias')::integer;
  end if;

  -- Queda en la bitácora antes de borrar: después ya no habría de
  -- dónde sacar quién era.
  begin
    insert into public.auditoria (tabla, registro_id, operacion, autor_email, antes)
    values ('auth.users', p_usuario::text, 'eliminar_usuario', v_email, v_resumen);
  exception when others then
    raise warning 'eliminar_usuario/auditoria: %', sqlerrm;
  end;

  -- Antes del recorrido: las respuestas que cuelgan de un hilo suyo.
  -- El recorrido va por orden alfabético, así que `foro_hilos` se
  -- borraría antes que `foro_respuestas` y la llave foránea pararía el
  -- borrado entero con un error que no dice cuál fue el problema.
  delete from public.foro_respuestas r
   using public.foro_hilos h
   where r.hilo_id = h.id and h.autor_id = p_usuario;

  for v_tabla in
    select c.table_name, c.column_name
      from information_schema.columns c
      join information_schema.tables t
        on t.table_schema = c.table_schema and t.table_name = c.table_name
     where c.table_schema = 'public'
       and c.column_name in ('usuario_id', 'autor_id')
       and c.data_type = 'uuid'
       and t.table_type = 'BASE TABLE'
       -- La bitácora no se borra: es el registro de quién hizo qué y
       -- sobrevive a la persona. Su `autor_id` se desliga más abajo.
       and c.table_name <> 'auditoria'
     order by c.table_name
  loop
    execute format('delete from public.%I where %I = $1', v_tabla.table_name, v_tabla.column_name)
      using p_usuario;
    get diagnostics v_n = row_count;
    if v_n > 0 then
      v_borradas := v_borradas || jsonb_build_object(
        v_tabla.table_name, coalesce((v_borradas ->> v_tabla.table_name)::integer, 0) + v_n);
    end if;
  end loop;

  -- Columnas que apuntan a la cuenta sin ser suyas: se desligan, no
  -- se borra la fila (la calificación que puso sigue valiendo).
  update public.auditoria set autor_id = null where autor_id = p_usuario;
  update public.foro_respuestas set calificado_por = null where calificado_por = p_usuario;

  delete from public.perfiles where id = p_usuario;

  begin
    delete from auth.users where id = p_usuario;
  exception when foreign_key_violation then
    -- Una tabla nueva guarda su id con otro nombre de columna. Mejor
    -- decir cuál que devolver el error crudo de Postgres.
    raise exception 'No se pudo borrar la cuenta: algo más la sigue referenciando (%). Avisa para añadir esa tabla al borrado.', sqlerrm;
  end;

  return jsonb_build_object('email', v_obj, 'borradas', v_borradas);
end
$$;

revoke all on function public.eliminar_usuario(uuid, text) from public;
grant execute on function public.eliminar_usuario(uuid, text) to authenticated;

notify pgrst, 'reload schema';

