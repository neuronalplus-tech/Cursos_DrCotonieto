-- =============================================================
--  APUNTES PERSONALES DEL ALUMNO
--
--  QUÉ RESUELVE
--  El alumno no tiene dónde tomar notas mientras estudia un módulo.
--  Esto le da un bloc privado por módulo: lo escribe él, lo ve solo
--  él. Ni el docente ni el administrador lo leen (es un espacio
--  personal, no una entrega).
--
--  DISEÑO
--  Una fila por (usuario, módulo): al guardar se hace upsert, así no
--  se acumulan versiones. La privacidad vive en la RLS: cada quien
--  solo toca lo suyo (usuario_id = auth.uid()), en lectura y en
--  escritura. No hay política de admin a propósito: un apunte
--  personal no es de nadie más.
--
--  CÓMO SE INSTALA
--  Supabase -> SQL Editor -> New query -> pega esto -> Run.
--  Idempotente.
-- =============================================================

create table if not exists public.apuntes (
  id             bigint generated by default as identity primary key,
  usuario_id     uuid not null references auth.users(id) on delete cascade,
  modulo_id      bigint not null references public.modulos(id) on delete cascade,
  texto          text not null default '',
  actualizado_en timestamptz not null default now()
);

create unique index if not exists apuntes_usuario_modulo_idx
  on public.apuntes (usuario_id, modulo_id);

alter table public.apuntes enable row level security;

-- Cada quien, solo lo suyo. Un único `for all` cubre leer, escribir,
-- actualizar y borrar: todas con la misma condición.
drop policy if exists "apuntes_propios" on public.apuntes;
create policy "apuntes_propios" on public.apuntes
  for all to authenticated
  using (usuario_id = auth.uid())
  with check (usuario_id = auth.uid());

comment on table public.apuntes is
  'Notas privadas del alumno por módulo. Solo las ve y edita su dueño (ver RLS). No es una entrega: el docente no las lee.';

notify pgrst, 'reload schema';

