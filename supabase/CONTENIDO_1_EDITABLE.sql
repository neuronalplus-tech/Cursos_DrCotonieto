  (select count(*)::text from information_schema.tables
    where table_schema = 'public' and table_name = 'contenido_sitio') as n
union all
select 'politicas en contenido_sitio',
  (select count(*)::text from pg_policies
    where schemaname = 'public' and tablename = 'contenido_sitio');
