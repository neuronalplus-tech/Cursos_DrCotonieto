--
--  QUÉ RESUELVE
--  Buena parte de lo que se ve en el sitio estaba escrito en el
--  código: el perfil, el mensaje de WhatsApp, «Quiero
--  inscribirme», «Ya tengo acceso», «Saber más», servicios,
--  redes… Cambiar una palabra exigía programar y publicar. Otros
--  botones solo tenían candado (abrir/cerrar) y no se podían
--  eliminar.
--
--  CÓMO FUNCIONA
--  Una sola tabla, `contenido_sitio`, guarda una «capa de
--  edición» por elemento: clave -> valor (jsonb). El valor puede
--  traer texto, enlace, mensaje de WhatsApp, estilo, colores,
--  visible/oculto y eliminado. Lo que no está en la tabla se ve
--  exactamente como hoy: el código pone el valor por omisión y
--  la tabla solo lo SOBREESCRIBE. Restablecer = borrar la fila.
--
--  Una clave puede ser general («curso.inscribirme», vale para
--  todos los cursos) o de un solo elemento
--  («curso.inscribirme@curso:12»). Gana la más específica.
--
--  QUIÉN PUEDE QUÉ
--  · Leer: cualquiera, con o sin sesión. Es lo que ya se ve en
--    la página pública; no hay nada privado aquí.
--  · Escribir/borrar: solo quien administra esa organización
--    (`es_admin_de`). Filas sin organización = sitio principal:
--    solo el administrador de la plataforma (`es_admin()`).
--
--  POR QUÉ ADITIVO Y SEGURO
--  Tabla nueva, vacía al nacer: sin filas, el sitio se ve igual.
--  No se migra ni se toca ningún dato existente.
--
--  CÓMO USARLO
--  Supabase -> SQL Editor -> New query -> pega esto -> Run.
--  Idempotente: se puede correr varias veces.
-- =============================================================

create table if not exists public.contenido_sitio (
  id               bigint generated by default as identity primary key,
  organizacion_id  bigint references public.organizaciones(id)
    on delete cascade,
  clave            text not null check (length(clave) between 1 and 200),
  valor            jsonb not null default '{}'::jsonb,
  actualizado_en   timestamptz not null default now(),
  actualizado_por  text
);

-- Una fila por clave y organización (null = sitio principal).
create unique index if not exists contenido_sitio_clave_idx
  on public.contenido_sitio (coalesce(organizacion_id, 0), clave);

alter table public.contenido_sitio enable row level security;

drop policy if exists "contenido_sitio_leer" on public.contenido_sitio;
create policy "contenido_sitio_leer" on public.contenido_sitio
  for select to anon, authenticated
  using (true);

drop policy if exists "contenido_sitio_crear" on public.contenido_sitio;
create policy "contenido_sitio_crear" on public.contenido_sitio
  for insert to authenticated
  with check (
    case when organizacion_id is null then public.es_admin()
         else public.es_admin_de(organizacion_id) end
  );

drop policy if exists "contenido_sitio_editar" on public.contenido_sitio;
create policy "contenido_sitio_editar" on public.contenido_sitio
  for update to authenticated
  using (
    case when organizacion_id is null then public.es_admin()
         else public.es_admin_de(organizacion_id) end
  )
  with check (
    case when organizacion_id is null then public.es_admin()
         else public.es_admin_de(organizacion_id) end
  );

drop policy if exists "contenido_sitio_borrar" on public.contenido_sitio;
create policy "contenido_sitio_borrar" on public.contenido_sitio
  for delete to authenticated
  using (
    case when organizacion_id is null then public.es_admin()
         else public.es_admin_de(organizacion_id) end
  );

notify pgrst, 'reload schema';

